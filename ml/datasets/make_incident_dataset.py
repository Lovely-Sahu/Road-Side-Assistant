# Neutral context: tells the model that place, time and politeness words carry no signal.
CONTEXT = [
    "on the highway", "near the toll plaza", "while going to office", "at night", "in heavy traffic",
    "on NH16 near Cuttack", "please help", "please send someone quickly", "near Khandagiri",
    "on the way to Puri", "in the city", "outside the mall", "since this morning", "with my family in the car",
]


def build():
    rng = random.Random(42)
    # "group" ties a sentence to its context variants, so cross-validation can keep
    # all variants of one sentence in the same fold (no leakage between folds).
    train_rows, group = [], 0
    for label, sentences in TRAIN.items():
        for s in sentences:
            group += 1
            train_rows.append((s, label, group))
            for ctx in rng.sample(CONTEXT, 2):
                text = f"{s} {ctx}" if rng.random() < 0.6 else f"{ctx.capitalize()}, {s[0].lower()}{s[1:]}"
                train_rows.append((text, label, group))
    test_rows = [(s, label, i + 1) for i, (s, label) in enumerate((s, label) for label, sentences in TEST.items() for s in sentences)]

    train_texts = {t.lower() for t, _, _ in train_rows}
    overlap = [t for t, _, _ in test_rows if t.lower() in train_texts]
    assert not overlap, f"test sentences also in training data: {overlap}"

    for path, rows in ((TRAIN_CSV, train_rows), (TEST_CSV, test_rows)):
        with path.open("w", newline="", encoding="utf-8") as fh:
            writer = csv.writer(fh)
            writer.writerow(["text", "label", "group"])
            writer.writerows(rows)
    return len(train_rows), len(test_rows)


if __name__ == "__main__":
    n_train, n_test = build()
    print(f"Wrote {n_train} training rows to {TRAIN_CSV.name} and {n_test} test rows to {TEST_CSV.name}")
